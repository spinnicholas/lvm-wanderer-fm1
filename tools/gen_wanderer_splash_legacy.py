"""Generate small antialiased boot identity masks and an editable SVG master."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
import math,base64,sys
ROOT=Path(__file__).resolve().parents[1]
DEST=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'build/splash-art'
DEST.mkdir(parents=True,exist_ok=True)
S=8
fontpath=ROOT/'assets/AtkinsonHyperlegible-Bold.ttf'

def canvas():return Image.new('L',(240*S,240*S))
def cubic(points,n=80):
 out=[]
 for i in range(n+1):
  t=i/n;u=1-t
  out.append(tuple((u*u*u*points[0][k]+3*u*u*t*points[1][k]+3*u*t*t*points[2][k]+t*t*t*points[3][k])*S for k in range(2)))
 return out

def line(im,points,w):
 d=ImageDraw.Draw(im);d.line(points,fill=255,width=round(w*S),joint='curve')
 for x,y in points:
  r=w*S/2;d.ellipse((x-r,y-r,x+r,y+r),fill=255)

layers=[]
orbit=canvas();pts=[]
for i in range(321):
 t=math.radians(-20+i);a=math.radians(-20)
 x,y=66*math.cos(t),46*math.sin(t)
 pts.append(((120+x*math.cos(a)-y*math.sin(a))*S,(94+x*math.sin(a)+y*math.cos(a))*S))
line(orbit,pts,1.8);layers.append(('orbit',orbit))
signal=canvas();pts=[]
curves=[[(76,78),(85,78),(87,125),(99,125)],[(99,125),(108,125),(110,85),(120,85)],[(120,85),(130,85),(132,125),(142,125)],[(142,125),(154,125),(153,75),(164,62)]]
for curve in curves:pts+=cubic(curve)
line(signal,pts,7);layers.append(('signal',signal))
star=canvas();d=ImageDraw.Draw(star)
d.polygon([(164*S,50*S),(167*S,59*S),(176*S,62*S),(167*S,65*S),(164*S,74*S),(161*S,65*S),(152*S,62*S),(161*S,59*S)],fill=255)
layers.append(('star',star))
text=canvas();d=ImageDraw.Draw(text);font=ImageFont.truetype(str(fontpath),34*S)
word='Wanderer';w=d.textlength(word,font=font);d.text(((240*S-w)/2,165*S),word,font=font,fill=255,anchor='lt')
layers.append(('title',text))
brand=canvas();d=ImageDraw.Draw(brand);font=ImageFont.truetype(str(fontpath),14*S)
spacing=3*S;w=sum(d.textlength(c,font=font) for c in 'LVM')+spacing*2;x=(240*S-w)/2
for c in 'LVM':
 d.text((x,211*S),c,font=font,fill=255,anchor='lt');x+=d.textlength(c,font=font)+spacing
layers.append(('brand',brand))
header=['/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/gen_wanderer_splash.py */', 'typedef struct {uint16_t x,y,w,h;const uint16_t *row;const uint8_t *data;} splash_mask_t;']
for name,im in layers:
 im=im.resize((240,240),Image.Resampling.LANCZOS)
 # Quantized alpha prevents LANCZOS's nearly invisible fringe wasting flash.
 im=im.point(lambda a:round(a/17)*17)
 box=im.getbbox();im=im.crop(box);w,h=im.size;raw=[];offsets=[]
 for y in range(h):
  offsets.append(len(raw));vals=[im.getpixel((x,y))//17 for x in range(w)];x=0
  while x<w:
   a=vals[x];n=1
   while x+n<w and vals[x+n]==a and n<16:n+=1
   raw.append((a<<4)|(n-1));x+=n
 offsets.append(len(raw))
 header+=['static const uint16_t SPLASH_'+name+'_ROW[]={'+','.join(map(str,offsets))+'};','static const uint8_t SPLASH_'+name+'_DATA[]={'+','.join(map(str,raw))+'};',f'static const splash_mask_t SPLASH_{name}={{{box[0]},{box[1]},{w},{h},SPLASH_{name}_ROW,SPLASH_{name}_DATA}};']
(ROOT/'firmware/src/wanderer_splash_art.h').write_text('\n'.join(header)+'\n')
# SVG uses the same paths and embedded font for fully portable editing.
fontdata=base64.b64encode(fontpath.read_bytes()).decode()
svg=f'''<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240" viewBox="0 0 240 240"><style>@font-face{{font-family:Atkinson;src:url(data:font/ttf;base64,{fontdata})}}text{{font-family:Atkinson;font-weight:700}}</style><rect width="240" height="240" fill="#071318"/><g fill="none" stroke-linecap="round"><polyline points="{' '.join(f'{x/S:.3f},{y/S:.3f}' for x,y in pts)}" stroke="#8fe4d3" stroke-width="7"/><polyline points="{' '.join(f'{x/S:.3f},{y/S:.3f}' for x,y in [((120+66*math.cos(math.radians(-20+i))*math.cos(math.radians(-20))-46*math.sin(math.radians(-20+i))*math.sin(math.radians(-20)))*S,(94+66*math.cos(math.radians(-20+i))*math.sin(math.radians(-20))+46*math.sin(math.radians(-20+i))*math.cos(math.radians(-20)))*S) for i in range(321)])}" stroke="#739897" stroke-width="1.8"/></g><path d="M164 50 167 59 176 62 167 65 164 74 161 65 152 62 161 59Z" fill="#f5cf91"/><text x="120" y="189" text-anchor="middle" font-size="34" fill="#f1f3e8">Wanderer</text><text x="120" y="221" text-anchor="middle" font-size="14" letter-spacing="3" fill="#b8ccc4">LVM</text></svg>'''
(DEST/'LVM-Wanderer-Boot-Refined.svg').write_text(svg)
print('Generated antialiased masks:',sum(len(x) for x in header),'C source characters')

#!/usr/bin/env python3
"""Generate original, band-limited oscillator tables for the FM-1 voice engine."""
import math
import sys
from pathlib import Path

HARMONICS = (1, 2, 4, 8, 12)
N = 256
SHAPES = ("saw", "hollow", "glass")


def sample(shape, phase, limit):
    result = 0.0
    for h in range(1, limit + 1):
        if shape == "saw":
            weight = (-1 if h % 2 == 0 else 1) / h
        elif shape == "hollow":
            weight = 1 / h if h % 2 else 0
        else:
            weight = {1: 1.0, 2: .34, 3: .19, 5: .11, 7: .06}.get(h, 0)
        result += weight * math.sin(2 * math.pi * h * phase)
    return result


def main(out):
    banks = []
    for shape in SHAPES:
        for limit in HARMONICS:
            values = [sample(shape, i / N, limit) for i in range(N)]
            peak = max(abs(x) for x in values)
            banks.extend(round(x * 26000 / peak) for x in values)
    lines = [
        "/* Original LVM band-limited oscillator tables; generated by tools/gen_wanderer_waves.py. */",
        "#pragma once",
        "#define WAVE_SAW 0u",
        "#define WAVE_HOLLOW 1u",
        "#define WAVE_GLASS 2u",
        "#define WAVE_LENGTH 256u",
        "static const int16_t WANDERER_WAVE[3][5][256] = {",
    ]
    for shape in range(3):
        lines.append("  {")
        for band in range(5):
            v = banks[(shape * 5 + band) * N:(shape * 5 + band + 1) * N]
            lines.append("    {")
            for i in range(0, N, 12):
                lines.append("      " + ", ".join(str(x) for x in v[i:i+12]) + ",")
            lines.append("    },")
        lines.append("  },")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"{len(banks) * 2} bytes of band-limited oscillator tables")


if __name__ == "__main__":
    main(sys.argv[1])
